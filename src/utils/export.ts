/**
 * Export Utilities: CSV and Formatted Text Generation
 */

import { EventPlan } from '../types/event';
import { formatCurrency, toMajorUnits } from './currency';
import { formatDisplayDate } from './timeline';

/**
 * Escapes a cell value for standard CSV format
 */
function escapeCsvCell(val: unknown): string {
  if (val === undefined || val === null) return '""';
  const str = String(val).replace(/"/g, '""');
  return `"${str}"`;
}

/**
 * Downloads a text or CSV file in the browser
 */
export function downloadFile(content: string, filename: string, mimeType = 'text/csv;charset=utf-8;') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', filename);
  link.style.visibility = 'hidden';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/**
 * Generates CSV for the Budget breakdown
 */
export function exportBudgetToCsv(plan: EventPlan) {
  const currency = plan.budget.currency || 'INR';
  const headers = [
    'Category',
    'Description',
    `Estimated Amount (${currency})`,
    `Actual Amount (${currency})`,
    'Quantity',
    `Unit Cost (${currency})`,
    'Priority',
    'Payment Status',
    'Notes',
  ];

  const rows = (plan.budget.items || []).map((item) => [
    escapeCsvCell(item.category),
    escapeCsvCell(item.description),
    escapeCsvCell(toMajorUnits(item.estimatedAmountMinor, currency)),
    escapeCsvCell(toMajorUnits(item.actualAmountMinor, currency)),
    escapeCsvCell(item.quantity),
    escapeCsvCell(toMajorUnits(item.unitCostMinor, currency)),
    escapeCsvCell(item.priority),
    escapeCsvCell(item.paymentStatus),
    escapeCsvCell(item.notes || ''),
  ]);

  const csvContent = [headers.map(escapeCsvCell).join(','), ...rows.map((r) => r.join(','))].join('\n');
  const filename = `${plan.eventDetails.name.toLowerCase().replace(/[^a-z0-9]/g, '_')}_budget.csv`;
  downloadFile(csvContent, filename);
}

